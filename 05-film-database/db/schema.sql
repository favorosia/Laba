CREATE TABLE IF NOT EXISTS movies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL CHECK (length(trim(title)) > 0),
    release_year INTEGER NOT NULL CHECK (release_year BETWEEN 1888 AND 2100),
    CONSTRAINT uq_movies_title_year UNIQUE (title, release_year)
);

CREATE TABLE IF NOT EXISTS actors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(180) NOT NULL CHECK (length(trim(full_name)) > 0),
    birth_year INTEGER NOT NULL CHECK (birth_year BETWEEN 1850 AND 2026),
    CONSTRAINT uq_actors_name_birth UNIQUE (full_name, birth_year)
);

CREATE TABLE IF NOT EXISTS film_roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NOT NULL REFERENCES actors(id) ON DELETE CASCADE,
    movie_id BIGINT NOT NULL REFERENCES movies(id) ON DELETE CASCADE,
    role_name VARCHAR(120) NOT NULL CHECK (length(trim(role_name)) > 0),
    CONSTRAINT uq_film_roles_assignment UNIQUE (actor_id, movie_id, role_name)
);

CREATE INDEX IF NOT EXISTS ix_movies_title ON movies (title);
CREATE INDEX IF NOT EXISTS ix_actors_name ON actors (full_name);
CREATE INDEX IF NOT EXISTS ix_film_roles_actor ON film_roles (actor_id);
CREATE INDEX IF NOT EXISTS ix_film_roles_movie ON film_roles (movie_id);
